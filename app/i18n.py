def detect_default_language() -> str:
    """Kullanıcının Windows sistem diline göre varsayılan dili seçer (varsayılan 'en', Türkçe ise 'tr')."""
    try:
        loc = (locale.getlocale()[0] or "").lower()
    except Exception:
        loc = ""
    for code, _ in SUPPORTED_LANGUAGES:
        if loc.startswith(code):
            return code
    return "en"


def tr(lang_code: str, key: str, **kwargs: Any) -> str:
    bucket = TRANSLATIONS.get(lang_code) or TRANSLATIONS["en"]
    tmpl = bucket.get(key) or TRANSLATIONS["en"].get(key) or TRANSLATIONS["tr"].get(key) or key
    try:
        return tmpl.format(**kwargs) if kwargs else tmpl
    except Exception:
        return tmpl
