def _system_language_tags() -> list[str]:
    """Return system language tags in ISO format (e.g. 'tr_TR', 'en_US')."""
    tags: list[str] = []
    try:
        import ctypes

        lcid = int(ctypes.windll.kernel32.GetUserDefaultUILanguage())
        tag = locale.windows_locale.get(lcid, "")
        if tag:
            tags.append(tag)
    except Exception:
        pass
    try:
        from PySide6.QtCore import QLocale

        tags.append(QLocale.system().name())
    except Exception:
        pass
    try:
        tags.append(locale.getlocale()[0] or "")
    except Exception:
        pass
    return [t for t in tags if t]


def detect_default_language() -> str:
    """Pick a supported language matching the OS UI locale (defaults to 'en')."""
    supported = {code for code, _ in SUPPORTED_LANGUAGES}
    for tag in _system_language_tags():
        code = tag.replace("-", "_").split("_")[0].lower()
        if code in supported:
            return code
    return "en"


def normalize_language(lang_code: str) -> str:
    code = (lang_code or "").strip().lower()
    supported = {c for c, _ in SUPPORTED_LANGUAGES}
    return code if code in supported else detect_default_language()


def tr(lang_code: str, key: str, **kwargs: Any) -> str:
    bucket = TRANSLATIONS.get(lang_code) or TRANSLATIONS["en"]
    tmpl = bucket.get(key) or TRANSLATIONS["en"].get(key) or key
    try:
        return tmpl.format(**kwargs) if kwargs else tmpl
    except Exception:
        return tmpl
